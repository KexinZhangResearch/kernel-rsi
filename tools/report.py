#!/usr/bin/env python3
"""Summarize a work directory and export the verified replacements.

  report.py <work dir>            # the dir that holds the region dirs created by region.py

Writes <work>/REPORT.md (every region: attempts, failures, best verified result; every whole-model
check per shape) and <work>/krsi_patch.py with `apply(model)`, which installs the replacements whose
latest swap.py run passed — the way to use the results in your own code:

    import krsi_patch; krsi_patch.apply(model)      # same model class / module names as model_entry.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def load(p: Path):
    try:
        return json.loads(p.read_text())
    except (OSError, ValueError):
        return None


def fmt(x, spec=".2f"):
    return "-" if x is None else format(x, spec)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    work = Path(sys.argv[1]).resolve()
    regions = sorted(p.parent for p in work.rglob("region.json"))
    lines = [f"# kernel-rsi report — {work}", ""]
    passing = []
    lines += ["## Regions", "",
              "| region | mode | attempts | failed | best verified speedup (vs eager / vs best baseline) | ceiling | latest swap |",
              "|---|---|---|---|---|---|---|"]
    details = []
    for d in regions:
        meta = load(d / "region.json") or {}
        runs = [(p, load(p)) for p in sorted((d / "results").glob("[0-9][0-9][0-9].json"))]
        runs = [(p, r) for p, r in runs if r]
        ok = [(p, r) for p, r in runs if r.get("correct") and r.get("speedup")]
        best = max(ok, key=lambda pr: pr[1]["speedup"], default=None)
        swaps = [(p, load(p)) for p in sorted((d / "results").glob("swap_[0-9][0-9][0-9].json"))]
        swaps = [(p, s) for p, s in swaps if s]
        last = swaps[-1] if swaps else None
        swap_txt = "-"
        if last:
            s = last[1]
            swap_txt = (f"{'PASS' if s.get('correct') else 'FAIL'} {fmt(s.get('speedup_device_ms'), '.2f')}x "
                        f"({last[0].name})")
            if s.get("correct") and s.get("patched"):
                passing.append((d, s))
        best_txt = (f"{best[1]['speedup']:.2f}x / {best[1].get('speedup_vs_best_baseline', best[1]['speedup']):.2f}x "
                    f"({best[0].name}, {', '.join(f'{k}: {v}' for k, v in (best[1].get('significance') or {}).items())})"
                    if best else "none")
        lines.append(f"| {d.name} (`{meta.get('module')}`) | {meta.get('mode', 'infer')}"
                     f"{', AMP ' + meta['autocast']['dtype'] if meta.get('autocast') else ''} | {len(runs)} | "
                     f"{sum(not r.get('correct') for _, r in runs)} | {best_txt} | {meta.get('ceiling_us')} us | {swap_txt} |")
        details += [f"### {d.name}", ""]
        for p, r in runs:
            t = (r.get("timing") or {}).get("impl", {})
            details.append(f"- {p.name}: {'PASS' if r.get('correct') else 'FAIL'}"
                           + (f", {r['speedup']:.2f}x, {t.get('device_ms', 0) * 1000:.1f} us" if r.get("speedup") else "")
                           + (f" — {r['note']}" if r.get("note") else ""))
        for p, s in swaps:
            per = s.get("timing") or {}
            shape_txt = "; ".join(f"{k}: {v['speedup']['device_ms']:.2f}x ({v['significance'].get('original')})"
                                  for k, v in per.items()) if isinstance(per, dict) and per and \
                all(isinstance(v, dict) and "speedup" in v for v in per.values()) else ""
            curve = s.get("train_curves", {}).get("verdict")
            if s.get("coverage_gaps"):
                shape_txt += " — NOT CHECKED: " + "; ".join(g.split(":")[0] for g in s["coverage_gaps"])
            details.append(f"- {p.name}: whole model {'PASS' if s.get('correct') else 'FAIL'}"
                           + (f"; {shape_txt}" if shape_txt else "") + (f"; loss curve {curve}" if curve else ""))
        notes = d / "NOTES.md"
        if notes.is_file():
            details.append(f"- notes: {notes}")
        details.append("")
    lines += ["", "## Details", ""] + details

    # Export: one patch per module qualname, from the latest passing swap of each region.
    patched = {}
    for d, s in passing:
        for q, region_dir, sha in s["patched"]:
            patched[q] = region_dir
    patch = ['"""Generated by kernel-rsi report.py: install the verified replacements into a model.',
             "", "    import krsi_patch; krsi_patch.apply(model)", "",
             "Each replacement passed swap.py on the whole model (results noted below). Re-run swap.py after",
             "changing the model, torch, or the GPU.", '"""', "import importlib.util", "import types", "",
             f"PATCHES = {json.dumps(patched, indent=4)}", "", "",
             "def _load(path):",
             "    spec = importlib.util.spec_from_file_location('krsi_impl_' + str(abs(hash(path))), path + '/impl.py')",
             "    mod = importlib.util.module_from_spec(spec)", "    spec.loader.exec_module(mod)", "    return mod",
             "", "", "def apply(model):", "    named = {(q or '<root>'): m for q, m in model.named_modules()}",
             "    impls = {d: _load(d) for d in set(PATCHES.values())}", "    for q, d in PATCHES.items():",
             "        m = named[q]",
             "        m.forward = types.MethodType(lambda self, *a, _i=impls[d], **k: _i.forward(self, *a, **k), m)",
             "    return model", "", "",
             "def remove(model):", "    named = {(q or '<root>'): m for q, m in model.named_modules()}",
             "    for q in PATCHES:", "        named[q].__dict__.pop('forward', None)", "    return model", ""]
    (work / "krsi_patch.py").write_text("\n".join(patch))
    lines += ["## Export", "",
              f"`{work / 'krsi_patch.py'}` installs {len(patched)} verified replacement(s): "
              + (", ".join(f"`{q}`" for q in patched) or "none (no passing swap.py run yet)") + ".",
              "It patches module instances in place (works for eager models; for torch.compile apply it before "
              "compiling, for FSDP/DDP before wrapping)."]
    (work / "REPORT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:len(regions) + 6]))
    print(f"\nwrote {work / 'REPORT.md'} and {work / 'krsi_patch.py'}")


if __name__ == "__main__":
    main()
